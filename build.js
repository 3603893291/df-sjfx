/* build.js — 组装免安装绿色版（增量打包）
 *
 * 策略：Electron 运行时体积大且从不变化，只在首次复制；
 * 之后的每次打包只重建体积很小的 resources/app（约 30 个文件），
 * 既能秒级完成，也避免对上千个文件做批量删除。
 *
 * 用法：node build.js [electron运行时目录]
 * 默认依次在下列位置寻找运行时：
 *   1. 环境变量 ELECTRON_DIST
 *   2. ./electron
 *   3. ../.workbuddy/electron-dist
 */
