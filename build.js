function findElectron() {
  const cands = [
    process.env.ELECTRON_DIST,
    path.join(ROOT, 'electron'),
    path.join(ROOT, '..', '.workbuddy', 'electron-dist')
  ].filter(Boolean);
  for (const c of cands) {
    if (fs.existsSync(path.join(c, 'electron.exe')) || fs.existsSync(path.join(c, 'electron'))) return c;
  }
  return null;
}

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const item of fs.readdirSync(src)) {
    const s = path.join(src, item);
    const d = path.join(dst, item);
    if (fs.statSync(s).isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

function rmDir(p) {
  if (!fs.existsSync(p)) return;
  for (const item of fs.readdirSync(p)) {
    const full = path.join(p, item);
    if (fs.statSync(full).isDirectory()) rmDir(full);
    else { try { fs.unlinkSync(full); } catch (e) { /* 被占用则跳过 */ } }
  }
  try { fs.rmdirSync(p); } catch (e) { /* ignore */ }
}

function dirSize(d) {
  let n = 0;
  (function walk(p) {
    for (const f of fs.readdirSync(p)) {
      const full = path.join(p, f);
      const st = fs.statSync(full);
      if (st.isDirectory()) walk(full); else n += st.size;
    }
  })(d);
  return n;
}

