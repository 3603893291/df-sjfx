/* 增量同步运行时：只补齐缺失或大小不符的文件（纯新增，不做删除）
 * 这样即使运行时被误删/被中断的打包损坏，也能自动修复 */
function syncRuntime(src, dst) {
  let copied = 0;
  fs.mkdirSync(dst, { recursive: true });
  for (const item of fs.readdirSync(src)) {
    const s = path.join(src, item);
    const d = path.join(dst, item);
    const st = fs.statSync(s);
    if (st.isDirectory()) {
      copied += syncRuntime(s, d);
    } else if (item === 'electron.exe' || item === 'electron' || item === 'Electron') {
      continue;                                  // 主程序单独改名处理
    } else if (item === 'default_app.asar') {
      continue;                                  // Electron 默认示例应用，绝不能带入
    } else if (!fs.existsSync(d) || fs.statSync(d).size !== st.size) {
      fs.copyFileSync(s, d);
      copied++;
    }
  }
  return copied;
}

function main() {
  const electronDir = findElectron();
  if (!electronDir) {
    console.error('未找到 Electron 运行时。请设置 ELECTRON_DIST 环境变量指向解压后的 electron 目录。');
    process.exit(1);
  }

  const base = path.join(ROOT, 'dist', OUT_NAME);
  let dist = base;
  const exeName = process.platform === 'win32' ? OUT_NAME + '.exe' : OUT_NAME;
  const exePath = path.join(dist, exeName);

  console.log('Electron 运行时：' + electronDir);
  console.log('输出目录：' + dist);

  // ---- 1. 运行时：缺失则整体复制，否则只补齐缺失文件 ----
  if (!fs.existsSync(exePath)) {
    console.log('首次打包，复制运行时…');
    try {
      copyDir(electronDir, dist);
      const exeSrc = ['electron.exe', 'electron', 'Electron']
        .map(n => path.join(dist, n)).find(p => fs.existsSync(p));
      if (exeSrc) fs.renameSync(exeSrc, exePath);
      const defApp = path.join(dist, 'resources', 'default_app.asar');
      if (fs.existsSync(defApp)) { try { fs.unlinkSync(defApp); } catch (e) {} }
    } catch (e) {
      console.error('复制运行时失败：' + (e.code || e.message));
      console.error('如果旧版本正在运行，请先关闭软件再重试。');
      process.exit(1);
    }
  } else {
    try {
      const n = syncRuntime(electronDir, dist);
      console.log(n > 0 ? ('运行时校验：补齐 ' + n + ' 个缺失文件。') : '运行时校验：完整。');
    } catch (e) {
      console.error('运行时校验失败：' + (e.code || e.message) + '（软件可能正在运行）');
      process.exit(1);
    }
  }

  // ---- 1.5 图标：每次都重打一遍 ----
  // 首次复制运行时会把 Electron 的默认图标一起带进来，所以这一步不能只在"没有图标"时做
  applyIcon(exePath);

  // ---- 2. 应用代码：每次重建（体积小） ----
  console.log('写入应用代码…');
  const appDir = path.join(dist, 'resources', 'app');

  // 必须移除 Electron 自带的默认示例应用，否则可能抢占应用入口
  const defApp = path.join(dist, 'resources', 'default_app.asar');
  if (fs.existsSync(defApp)) {
    try { fs.unlinkSync(defApp); console.log('已移除 default_app.asar'); }
    catch (e) { console.warn('移除 default_app.asar 失败：' + (e.code || e.message)); }
  }

  try {
    rmDir(appDir);
  } catch (e) {
    console.error('清理旧应用代码失败：' + (e.code || e.message) + '（软件可能正在运行）');
    process.exit(1);
  }

  try {
    for (const [src, dst] of APP_FILES) {
      const s = path.join(ROOT, src);
      const d = path.join(appDir, dst);
      if (!fs.existsSync(s)) continue;
      if (fs.statSync(s).isDirectory()) copyDir(s, d);
      else { fs.mkdirSync(path.dirname(d), { recursive: true }); fs.copyFileSync(s, d); }
    }
  } catch (e) {
    console.error('写入应用代码失败：' + (e.code || e.message));
    console.error('如果旧版本正在运行，请先关闭软件再重试。');
    process.exit(1);
  }

  writeReadme(dist, exeName);

  console.log('\n打包完成：' + dist);
  console.log('主程序：' + exeName);
  console.log('体积：' + (dirSize(dist) / 1024 / 1024).toFixed(1) + ' MB');
}

main();

/* 把 app-icon/app.ico 写进 exe 的资源图标。
 * rcedit 不在本仓库里（它是 electron-builder 拉下来的工具），所以三处候选路径找一个：
 * 环境变量 RCEDIT → electron-builder 的 winCodeSign 缓存 → tools/ 下放的一份。
 * 找不到只警告不报错：打包照样出得来，只不过图标还是 Electron 那个 —— 但一定要说出口，
 * 静默交一个"以为换了其实没换"的图标，比直接失败难查得多。生成资产：node tools/make-icon.js */
function applyIcon(exePath) {
  const ico = path.join(ROOT, 'app-icon', 'app.ico');
  if (!fs.existsSync(ico)) { console.log('图标：没有 app-icon/app.ico，跳过。'); return; }
  if (process.platform !== 'win32') { console.log('图标：非 Windows 平台打包，跳过。'); return; }
  const rc = [process.env.RCEDIT,
    path.join(process.env.LOCALAPPDATA || '', 'electron-builder/Cache/winCodeSign/winCodeSign-2.6.0/rcedit-x64.exe'),
    path.join(ROOT, 'tools', 'rcedit-x64.exe')].find(p => p && fs.existsSync(p));
  if (!rc) { console.warn('图标：★ 本机没找到 rcedit-x64.exe，exe 仍是 Electron 默认图标。'); return; }
  try {
    require('child_process').execFileSync(rc, [exePath, '--set-icon', ico], { windowsHide: true, stdio: 'ignore' });
    console.log('图标：已写入 exe。');
  } catch (e) {
    console.warn('图标：★ rcedit 失败（' + (e.code || e.message) + '）—— 软件正在运行的话先关掉再打包。');
  }
}
